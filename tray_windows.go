//go:build windows

package main

import (
	"syscall"
	"unsafe"
)

const trayMessage = 0x8000 + 81

// NOTIFYICONDATAW, including the x64 alignment padding supplied by Go.
type notifyIconData struct {
	Size                uint32
	Window              uintptr
	ID, Flags, Callback uint32
	Icon                uintptr
	Tip                 [128]uint16
	State, StateMask    uint32
	Info                [256]uint16
	Version             uint32
	InfoTitle           [64]uint16
	InfoFlags           uint32
	GUID                [16]byte
	BalloonIcon         uintptr
}

// The release target is Windows x64; reject an ABI layout change at build time.
var _ [976 - unsafe.Sizeof(notifyIconData{})]byte
var _ [unsafe.Sizeof(notifyIconData{}) - 976]byte

var tray struct {
	icon, smallIcon uintptr
	taskbarCreated  uint32
	added           bool
}
var trayShell = syscall.NewLazyDLL("shell32.dll")

func loadAppIcons(instance uintptr) {
	// The first RT_GROUP_ICON generated by rsrc has resource ID 1.
	tray.icon = call(user, "LoadImageW", instance, 1, 1, 32, 32, 0)
	tray.smallIcon = call(user, "LoadImageW", instance, 1, 1, 16, 16, 0)
	tray.taskbarCreated = uint32(call(user, "RegisterWindowMessageW", uintptr(unsafe.Pointer(wide("TaskbarCreated")))))
}
func releaseAppIcons() {
	if tray.icon != 0 {
		call(user, "DestroyIcon", tray.icon)
	}
	if tray.smallIcon != 0 {
		call(user, "DestroyIcon", tray.smallIcon)
	}
}
func trayData() notifyIconData {
	d := notifyIconData{Size: uint32(unsafe.Sizeof(notifyIconData{})), Window: desktop.h, ID: 1, Flags: 7, Callback: trayMessage, Icon: tray.smallIcon}
	tip, _ := syscall.UTF16FromString(appDisplayName + tr(" · 双击打开，右键退出"))
	copy(d.Tip[:], tip)
	return d
}
func addTray() bool {
	if tray.added {
		return true
	}
	if tray.smallIcon == 0 || desktop.h == 0 {
		return false
	}
	d := trayData()
	tray.added = call(trayShell, "Shell_NotifyIconW", 0, uintptr(unsafe.Pointer(&d))) != 0
	return tray.added
}
func updateTrayTip() {
	d := trayData()
	d.Flags = 4 // NIF_TIP
	call(trayShell, "Shell_NotifyIconW", 1, uintptr(unsafe.Pointer(&d)))
}
func removeTray() {
	if !tray.added {
		return
	}
	d := trayData()
	call(trayShell, "Shell_NotifyIconW", 2, uintptr(unsafe.Pointer(&d)))
	tray.added = false
}
func showMainWindow() {
	call(user, "ShowWindow", desktop.h, 9)
	call(user, "SetForegroundWindow", desktop.h)
}
func hideToTray() {
	if !addTray() {
		message(tr("暂时无法创建托盘图标，窗口保持打开，监控继续运行。"))
		return
	}
	for _, h := range []uintptr{desktop.detailWindow, desktop.diagnosticWindow} {
		if h != 0 {
			call(user, "ShowWindow", h, 0)
		}
	}
	call(user, "ShowWindow", desktop.h, 0)
}
func trayEvent(event uint32) {
	switch event {
	case 0x203, 0x400, 0x401: // Double-click, keyboard/select notifications.
		showMainWindow()
	case 0x205, 0x7b:
		menu := call(user, "CreatePopupMenu")
		if menu == 0 {
			return
		}
		defer call(user, "DestroyMenu", menu)
		call(user, "AppendMenuW", menu, 0, 1, uintptr(unsafe.Pointer(wide(tr("打开主窗口")))))
		call(user, "AppendMenuW", menu, 0x800, 0, 0)
		call(user, "AppendMenuW", menu, 0, 2, uintptr(unsafe.Pointer(wide(tr("退出程序（停止监控）")))))
		var p point
		call(user, "GetCursorPos", uintptr(unsafe.Pointer(&p)))
		call(user, "SetForegroundWindow", desktop.h)
		selected := call(user, "TrackPopupMenu", menu, 0x100|0x2, uintptr(p.X), uintptr(p.Y), 0, desktop.h, 0)
		call(user, "PostMessageW", desktop.h, 0, 0, 0)
		if selected == 1 {
			showMainWindow()
		}
		if selected == 2 {
			call(user, "DestroyWindow", desktop.h)
		}
	}
}
